const STATUS: Record<'nl' | 'en', Record<BookStatus, string>> = {
  nl: { 'te-lezen': 'te-lezen', lezend: 'lezend', uit: 'uit', gestaakt: 'gestaakt' },
  en: { 'te-lezen': 'to read', lezend: 'reading', uit: 'finished', gestaakt: 'stopped' }
};

export type T = (key: Key, vars?: Record<string, string | number>) => string;

/** Vertaalfunctie voor deze module; volgt de taalkeuze van Taskgram. */
export function useT() {
  const lang = useLang();
  const dict = lang === 'en' ? en : nl;
  const t: T = (key, vars) => dict[key].replace(/\{(\w+)\}/g, (_, v: string) => String(vars?.[v] ?? `{${v}}`));
  return { t, lang, status: (s: BookStatus) => STATUS[lang][s], locale: lang === 'en' ? 'en-GB' : 'nl-NL' };
}
